import "server-only";
import ExcelJS from "exceljs";
import { jsPDF } from "jspdf";
import { autoTable } from "jspdf-autotable";
import { LOGO_HEIGHT, LOGO_PNG_BASE64, LOGO_WIDTH } from "@/lib/brand/logo-data";
import type { DocRow, ReportDocument } from "./types";

const LOGO_DATA_URL = `data:image/png;base64,${LOGO_PNG_BASE64}`;

// Excel number format with lakh and crore grouping.
const INDIAN_FORMAT = "[>=10000000]##\\,##\\,##\\,##0.00;[>=100000]##\\,##\\,##0.00;##,##0.00";

const BOLD_STYLES = new Set(["group", "sub", "subtotal", "total"]);

function headerLines(doc: ReportDocument): string[] {
  return [
    doc.title,
    [doc.hotelName, doc.period].filter(Boolean).join(". "),
    doc.filters,
    `Generated by ${doc.generatedBy} on ${doc.generatedAt}.`,
  ].filter(Boolean);
}

export function fileName(doc: ReportDocument, extension: string): string {
  const safe = `${doc.title} ${doc.period}`.replace(/[^A-Za-z0-9]+/g, "-").replace(/^-|-$/g, "");
  return `${safe}.${extension}`;
}

export async function buildExcel(doc: ReportDocument): Promise<Buffer> {
  const workbook = new ExcelJS.Workbook();
  const sheet = workbook.addWorksheet(doc.title.slice(0, 31));

  // The logo sits in three blank rows at the top.
  const logo = workbook.addImage({ base64: LOGO_PNG_BASE64, extension: "png" });
  for (let i = 0; i < 3; i += 1) sheet.addRow([]).height = 20;
  sheet.addImage(logo, {
    tl: { col: 0, row: 0 },
    ext: { width: 168, height: Math.round((168 * LOGO_HEIGHT) / LOGO_WIDTH) },
  });

  const widest = Math.max(1, ...doc.tables.map((t) => t.columns.length));
  headerLines(doc).forEach((line, index) => {
    const excelRow = sheet.addRow([line]);
    excelRow.getCell(1).font = { bold: index === 0, size: index === 0 ? 14 : 10 };
  });
  sheet.addRow([]);

  for (const kpi of doc.kpis) {
    const excelRow = sheet.addRow([kpi.label, kpi.value, kpi.sub ?? ""]);
    excelRow.getCell(1).font = { bold: true };
  }
  if (doc.kpis.length > 0) sheet.addRow([]);

  for (const table of doc.tables) {
    if (table.heading) {
      sheet.addRow([table.heading]).getCell(1).font = { bold: true, size: 12 };
    }
    const head = sheet.addRow(table.columns.map((c) => c.label));
    head.eachCell((cell, colNumber) => {
      cell.font = { bold: true };
      cell.fill = { type: "pattern", pattern: "solid", fgColor: { argb: "FFF1F1F4" } };
      cell.alignment = { horizontal: table.columns[colNumber - 1]?.align === "right" ? "right" : "left" };
    });
    for (const rowItem of table.rows) {
      const excelRow = sheet.addRow(
        rowItem.cells.map((cell) => (cell.value !== undefined ? cell.value : cell.text)),
      );
      excelRow.eachCell({ includeEmpty: true }, (cell, colNumber) => {
        const column = table.columns[colNumber - 1];
        if (column?.align === "right") cell.alignment = { horizontal: "right" };
        if (typeof cell.value === "number") cell.numFmt = INDIAN_FORMAT;
        if (BOLD_STYLES.has(rowItem.style)) cell.font = { bold: true };
        if (rowItem.style === "void") cell.font = { color: { argb: "FF6E6E73" }, strike: true };
      });
    }
    sheet.addRow([]);
  }

  if (doc.notes.length > 0) {
    sheet.addRow(["Notes"]).getCell(1).font = { bold: true };
    for (const note of doc.notes) sheet.addRow([note]);
  }

  for (let column = 1; column <= widest; column += 1) {
    sheet.getColumn(column).width = column === 1 ? 34 : 18;
  }

  const buffer = await workbook.xlsx.writeBuffer();
  return Buffer.from(buffer);
}

export function buildPdf(doc: ReportDocument): Buffer {
  // Wide tables print better across the page.
  const widest = Math.max(1, ...doc.tables.map((t) => t.columns.length));
  const pdf = new jsPDF({ orientation: widest > 4 ? "landscape" : "portrait", unit: "pt", format: "a4" });
  const margin = 36;
  let y = margin;

  // The logo, then the title lines.
  const logoWidth = 110;
  const logoHeight = (logoWidth * LOGO_HEIGHT) / LOGO_WIDTH;
  pdf.addImage(LOGO_DATA_URL, "PNG", margin, y - 8, logoWidth, logoHeight);
  y += logoHeight + 10;

  headerLines(doc).forEach((line, index) => {
    pdf.setFont("helvetica", index === 0 ? "bold" : "normal");
    pdf.setFontSize(index === 0 ? 15 : 9);
    pdf.text(line, margin, y);
    y += index === 0 ? 18 : 12;
  });
  y += 4;

  if (doc.kpis.length > 0) {
    pdf.setFontSize(9);
    pdf.setFont("helvetica", "normal");
    pdf.text(doc.kpis.map((k) => `${k.label}: ${k.value}`).join("    "), margin, y);
    y += 16;
  }

  for (const table of doc.tables) {
    if (table.heading) {
      pdf.setFont("helvetica", "bold");
      pdf.setFontSize(11);
      pdf.text(table.heading, margin, y);
      y += 6;
    }
    autoTable(pdf, {
      startY: y,
      margin: { left: margin, right: margin },
      head: [table.columns.map((c) => c.label)],
      body: table.rows.map((rowItem: DocRow) =>
        rowItem.cells.map((cell) => cell.text),
      ),
      styles: { fontSize: 8, cellPadding: 3 },
      headStyles: { fillColor: [241, 241, 244], textColor: 40, fontStyle: "bold" },
      columnStyles: Object.fromEntries(
        table.columns.map((c, index) => [index, { halign: c.align === "right" ? "right" : "left" }]),
      ),
      didParseCell: (hook) => {
        if (hook.section !== "body") return;
        const style = table.rows[hook.row.index]?.style;
        if (style && BOLD_STYLES.has(style)) hook.cell.styles.fontStyle = "bold";
        if (style === "void") hook.cell.styles.textColor = [110, 110, 115];
        if (style === "group") hook.cell.styles.fillColor = [243, 243, 246];
        if (style === "total") hook.cell.styles.fillColor = [250, 250, 251];
      },
    });
    const last = (pdf as unknown as { lastAutoTable?: { finalY: number } }).lastAutoTable;
    y = (last?.finalY ?? y) + 14;
  }

  if (doc.notes.length > 0) {
    pdf.setFont("helvetica", "bold");
    pdf.setFontSize(9);
    pdf.text("Notes", margin, y);
    y += 11;
    pdf.setFont("helvetica", "normal");
    pdf.setFontSize(8);
    const pageWidth = pdf.internal.pageSize.getWidth() - margin * 2;
    for (const note of doc.notes) {
      const lines = pdf.splitTextToSize(`- ${note}`, pageWidth) as string[];
      if (y + lines.length * 10 > pdf.internal.pageSize.getHeight() - margin) {
        pdf.addPage();
        y = margin;
      }
      pdf.text(lines, margin, y);
      y += lines.length * 10 + 2;
    }
  }

  return Buffer.from(pdf.output("arraybuffer"));
}
