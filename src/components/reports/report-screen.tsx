import { usePathname, useRouter } from "next/navigation";
import { useEffect, useId, useState, useTransition } from "react";
import { flushSync } from "react-dom";
import type { ReactNode } from "react";
import { badge, button, field } from "@/components/ui/styles";
import type {
  DocRow,
  DocTable,
  FilterField,
  ReportDocument,
  RowStyle,
} from "@/lib/reports/types";

// All visible text sits here so it can be translated later.
const text = {
  print: "Print",
  excel: "Excel",
  pdf: "PDF",
  layout: "Layout",
  layoutRows: "Rows",
  layoutBlocks: "Voucher Blocks",
  notes: "Notes",
  generatedBy: "Generated by",
  on: "on",
  updating: "Updating the report...",
  void: "Void",
  rowsPerPage: "Rows per page",
  showing: (from: number, to: number, total: number) =>
    `Showing ${from} to ${to} of ${total}`,
  first: "First",
  previous: "Previous",
  next: "Next",
  last: "Last",
  pageOf: (page: number, pages: number) => `Page ${page} of ${pages}`,
  pagerLabel: "Pages",
  totalsNote: "Totals cover every row, not only this page.",
} as const;

// Rows per page. Entries are listed newest first.
const PAGE_SIZES = [10, 25, 50, 100, 200];
const DEFAULT_SIZE = 10;

type PagerState = { page: number; size: number };

// Rows per page, and First, Previous, Next and Last, under a paged list.
function Pager({
  total,
  state,
  onChange,
}: {
  total: number;
  state: PagerState;
  onChange: (next: PagerState) => void;
}) {
  const selectId = useId();
  const pages = Math.max(1, Math.ceil(total / state.size));
  const page = Math.min(state.page, pages - 1);
  const from = total === 0 ? 0 : page * state.size + 1;
  const to = Math.min(total, (page + 1) * state.size);
  const nav = `${button.secondary} ${button.small} min-w-[72px]`;
  return (
    <nav
      aria-label={text.pagerLabel}
      className="flex flex-wrap items-center justify-between gap-x-4 gap-y-2.5 border-t border-divider px-3.5 py-3 text-[0.84rem] print:hidden"
    >
      <div className="flex flex-wrap items-center gap-x-3 gap-y-1.5">
        <label htmlFor={selectId} className="text-muted">
          {text.rowsPerPage}
        </label>
        <select
          id={selectId}
          value={state.size}
          onChange={(event) =>
            onChange({ page: 0, size: Number(event.target.value) })
          }
          className={`${field.input} !h-10 !w-auto min-w-[84px] sm:!h-9`}
        >
          {PAGE_SIZES.map((size) => (
            <option key={size} value={size}>
              {size}
            </option>
          ))}
        </select>
        <span className="text-muted tabular-nums">
          {text.showing(from, to, total)}
        </span>
      </div>
      <div className="flex flex-wrap items-center gap-1.5">
        <button
          type="button"
          className={nav}
          disabled={page === 0}
          onClick={() => onChange({ ...state, page: 0 })}
        >
          {text.first}
        </button>
        <button
          type="button"
          className={nav}
          disabled={page === 0}
          onClick={() => onChange({ ...state, page: page - 1 })}
        >
          {text.previous}
        </button>
        <span className="px-1.5 text-muted tabular-nums">
          {text.pageOf(page + 1, pages)}
        </span>
        <button
          type="button"
          className={nav}
          disabled={page >= pages - 1}
          onClick={() => onChange({ ...state, page: page + 1 })}
        >
          {text.next}
        </button>
        <button
          type="button"
          className={nav}
          disabled={page >= pages - 1}
          onClick={() => onChange({ ...state, page: pages - 1 })}
        >
          {text.last}
        </button>
      </div>
    </nav>
  );
}

const ROW_CLASS: Record<RowStyle, string> = {
  normal: "",
  group: "bg-[#eff1f7] font-semibold",
  sub: "font-semibold",
  ledger: "",
  subtotal: "font-semibold",
  total: "border-t border-border-soft bg-[#f8f9fc] font-semibold",
  void: "text-muted line-through",
};

// Indent the first cell of group, sub-group and ledger rows.
const INDENT: Partial<Record<RowStyle, string>> = {
  sub: "pl-8",
  ledger: "pl-[50px]",
};

function ReportTable({ table, rows }: { table: DocTable; rows?: DocRow[] }) {
  return (
    <div className="overflow-x-auto">
      <table className="w-full border-collapse text-[0.88rem]">
        <thead>
          <tr className="border-b border-divider bg-[#f8f9fc] text-left text-[0.72rem] font-semibold uppercase tracking-[0.04em] text-muted">
            {table.columns.map((column, index) => (
              <th
                key={`${column.label}-${index}`}
                className={`whitespace-nowrap px-3.5 py-2.5 ${column.align === "right" ? "text-right" : ""}`}
              >
                {column.label}
              </th>
            ))}
          </tr>
        </thead>
        <tbody>
          {(rows ?? table.rows).map((rowItem: DocRow, rowIndex) => (
            <tr
              key={rowIndex}
              className={`border-b border-divider ${ROW_CLASS[rowItem.style]}`}
            >
              {rowItem.cells.map((cell, cellIndex) => {
                const column = table.columns[cellIndex];
                const right = column?.align === "right";
                return (
                  <td
                    key={cellIndex}
                    className={`px-3.5 py-2.5 align-top ${
                      right ? "whitespace-nowrap text-right tabular-nums" : ""
                    } ${cellIndex === 0 ? (INDENT[rowItem.style] ?? "") : ""}`}
                  >
                    {cell.text}
                  </td>
                );
              })}
            </tr>
          ))}
        </tbody>
      </table>
    </div>
  );
}

// A table drawn in a card. A paged table shows one page of its entries, keeps
// its Total rows under every page and has the pager at the bottom. When the page
// is printed every row is drawn.
function TableCard({
  table,
  pager,
  onPager,
  printAll,
}: {
  table: DocTable;
  pager: PagerState;
  onPager: (next: PagerState) => void;
  printAll: boolean;
}) {
  if (!table.paged) {
    return (
      <div className="overflow-hidden rounded-2xl bg-surface shadow-[0_1px_3px_rgba(0,0,0,0.05)]">
        <ReportTable table={table} />
      </div>
    );
  }
  const entries = table.rows.filter((item) => item.style !== "total");
  const totals = table.rows.filter((item) => item.style === "total");
  const pages = Math.max(1, Math.ceil(entries.length / pager.size));
  const page = Math.min(pager.page, pages - 1);
  const shown = printAll
    ? entries
    : entries.slice(page * pager.size, (page + 1) * pager.size);
  return (
    <div className="overflow-hidden rounded-2xl bg-surface shadow-[0_1px_3px_rgba(0,0,0,0.05)]">
      <ReportTable table={table} rows={[...shown, ...totals]} />
      {totals.length > 0 ? (
        <p className="px-3.5 pb-2 pt-1 text-[0.76rem] text-muted print:hidden">
          {text.totalsNote}
        </p>
      ) : null}
      <Pager total={entries.length} state={pager} onChange={onPager} />
    </div>
  );
}

function FilterBar({
  fields,
  values,
  onChange,
}: {
  fields: FilterField[];
  values: Record<string, string>;
  onChange: (name: string, value: string) => void;
}) {
  return (
    <div className="mb-3 flex flex-wrap items-end gap-x-2.5 gap-y-2 rounded-2xl bg-surface p-3 shadow-[0_1px_3px_rgba(0,0,0,0.05)] print:hidden">
      {fields.map((item) => {
        const id = `rf-${item.name}`;
        if (item.kind === "check") {
          return (
            <label
              key={item.name}
              htmlFor={id}
              className="inline-flex min-h-11 items-center gap-1.5 text-[0.85rem]"
            >
              <input
                id={id}
                type="checkbox"
                checked={values[item.name] === "1"}
                onChange={(event) =>
                  onChange(item.name, event.target.checked ? "1" : "")
                }
                className="h-[18px] w-[18px]"
              />
              {item.label}
            </label>
          );
        }
        return (
          <div key={item.name} className="grid min-w-0 gap-0.5">
            <label
              htmlFor={id}
              className="ml-0.5 text-[0.72rem] font-medium text-muted"
            >
              {item.label}
            </label>
            {item.kind === "date" ? (
              <input
                id={id}
                type="date"
                value={values[item.name] ?? ""}
                onChange={(event) => {
                  if (event.target.value)
                    onChange(item.name, event.target.value);
                }}
                className={`${field.input} sm:max-w-[170px]`}
              />
            ) : (
              <select
                id={id}
                value={values[item.name] ?? ""}
                onChange={(event) => onChange(item.name, event.target.value)}
                className={`${field.input} !w-auto min-w-[200px] max-w-full`}
              >
                {item.options.map((option) => (
                  <option key={option.value} value={option.value}>
                    {option.label}
                  </option>
                ))}
              </select>
            )}
          </div>
        );
      })}
    </div>
  );
}

export function ReportScreen({
  doc,
  fields,
  children,
}: {
  doc: ReportDocument;
  fields: FilterField[];
  children?: ReactNode;
}) {
  const router = useRouter();
  const pathname = usePathname();
  const [pending, startTransition] = useTransition();
  const [layout, setLayout] = useState<"rows" | "blocks">("rows");
  const [pager, setPager] = useState<PagerState>({
    page: 0,
    size: DEFAULT_SIZE,
  });
  const [printAll, setPrintAll] = useState(false);

  // A new report, or another layout, starts on the first page.
  const reportKey = `${doc.key}|${doc.period}|${doc.filters}|${doc.tables.map((t) => t.rows.length).join(",")}|${layout}`;
  const [seenReport, setSeenReport] = useState(reportKey);
  if (seenReport !== reportKey) {
    setSeenReport(reportKey);
    setPager((current) => ({ ...current, page: 0 }));
  }

  // Printing lists every row, not just the page on the screen.
  useEffect(() => {
    const before = () => flushSync(() => setPrintAll(true));
    const after = () => setPrintAll(false);
    window.addEventListener("beforeprint", before);
    window.addEventListener("afterprint", after);
    return () => {
      window.removeEventListener("beforeprint", before);
      window.removeEventListener("afterprint", after);
    };
  }, []);

  const initialValues = () =>
    Object.fromEntries(
      fields.map((item) => [
        item.name,
        item.kind === "check" ? (item.value ? "1" : "") : item.value,
      ]),
    );
  const [values, setValues] = useState<Record<string, string>>(initialValues);

  // When the server sends a report for new filters, show those filters.
  const fieldsKey = JSON.stringify(
    fields.map((item) => [item.name, item.value]),
  );
  const [seenKey, setSeenKey] = useState(fieldsKey);
  if (seenKey !== fieldsKey) {
    setSeenKey(fieldsKey);
    setValues(initialValues());
  }

  function queryFor(next: Record<string, string>): string {
    const query = new URLSearchParams();
    for (const [name, value] of Object.entries(next)) {
      if (value !== "") query.set(name, value);
    }
    return query.toString();
  }

  // Filters apply as soon as they change.
  function change(name: string, value: string) {
    const next = { ...values, [name]: value };
    setValues(next);
    startTransition(() => {
      router.replace(`${pathname}?${queryFor(next)}`, { scroll: false });
    });
  }

  const query = queryFor(values);
  const exportHref = (format: "xlsx" | "pdf") =>
    `/reports/export?report=${doc.key}&format=${format}${query ? `&${query}` : ""}`;

  const sideBySide = doc.sideBySide === true;

  return (
    <div>
      <div className="mb-3 flex flex-wrap items-start justify-between gap-3">
        <div>
          <h2 className="text-[1.35rem] font-semibold tracking-[-0.02em]">
            {doc.title}
          </h2>
          <p className="mt-0.5 text-[0.85rem] text-muted">
            {[doc.hotelName, doc.period].filter(Boolean).join(". ")}.{" "}
            {doc.filters ? `${doc.filters} ` : ""}
            {text.generatedBy} {doc.generatedBy} {text.on} {doc.generatedAt}.
          </p>
        </div>
        <div className="flex flex-wrap gap-1.5 print:hidden">
          <button
            type="button"
            onClick={() => window.print()}
            className={`${button.secondary} ${button.small}`}
          >
            {text.print}
          </button>
          <a
            href={exportHref("xlsx")}
            className={`${button.secondary} ${button.small}`}
          >
            {text.excel}
          </a>
          <a
            href={exportHref("pdf")}
            className={`${button.secondary} ${button.small}`}
          >
            {text.pdf}
          </a>
        </div>
      </div>

      <FilterBar fields={fields} values={values} onChange={change} />

      {doc.key === "day-book" && !doc.empty ? (
        <div
          className="mb-3 inline-flex gap-0.5 rounded-[10px] bg-track p-0.5 print:hidden"
          role="group"
          aria-label={text.layout}
        >
          {(["rows", "blocks"] as const).map((option) => (
            <button
              key={option}
              type="button"
              aria-pressed={layout === option}
              onClick={() => setLayout(option)}
              className={`min-h-9 rounded-lg px-3 text-[0.82rem] ${
                layout === option
                  ? "bg-surface font-semibold text-text shadow-[0_1px_3px_rgba(0,0,0,0.2)]"
                  : "font-medium text-muted hover:text-text"
              }`}
            >
              {option === "rows" ? text.layoutRows : text.layoutBlocks}
            </button>
          ))}
        </div>
      ) : null}

      <div
        aria-busy={pending}
        className={
          pending ? "opacity-60 transition-opacity" : "transition-opacity"
        }
      >
        <span role="status" className="sr-only">
          {pending ? text.updating : ""}
        </span>

        {doc.empty ? (
          <div className="rounded-2xl bg-surface px-4 py-9 text-center text-[0.9rem] text-muted shadow-[0_1px_3px_rgba(0,0,0,0.05)]">
            <strong className="mb-0.5 block text-[1rem] text-text">
              {doc.emptyTitle}
            </strong>
            {doc.emptyHint}
          </div>
        ) : (
          <>
            <div className="mb-3 grid grid-cols-2 gap-2.5 min-[900px]:grid-cols-4">
              {doc.kpis.map((item) => (
                <div
                  key={item.label}
                  className="rounded-2xl bg-surface px-3.5 py-3 shadow-[0_1px_3px_rgba(0,0,0,0.05)]"
                >
                  <div className="text-[0.74rem] font-medium uppercase tracking-[0.04em] text-muted">
                    {item.label}
                  </div>
                  <div className="mt-0.5 text-[1.25rem] font-semibold tracking-[-0.02em] tabular-nums">
                    {item.money ? "₹" : ""}
                    {item.value}
                  </div>
                  {item.sub ? (
                    <div className="text-[0.75rem] text-muted">{item.sub}</div>
                  ) : null}
                </div>
              ))}
            </div>

            {doc.key === "day-book" && layout === "blocks" && doc.blocks ? (
              <div className="overflow-hidden rounded-2xl bg-surface shadow-[0_1px_3px_rgba(0,0,0,0.05)]">
                <div className="grid gap-2.5 p-3">
                  {(printAll
                    ? doc.blocks
                    : doc.blocks.slice(
                        Math.min(
                          pager.page,
                          Math.max(
                            0,
                            Math.ceil(doc.blocks.length / pager.size) - 1,
                          ),
                        ) * pager.size,
                        (Math.min(
                          pager.page,
                          Math.max(
                            0,
                            Math.ceil(doc.blocks.length / pager.size) - 1,
                          ),
                        ) +
                          1) *
                          pager.size,
                      )
                  ).map((block) => (
                    <div
                      key={block.voucherId}
                      className={`overflow-hidden rounded-xl border border-divider ${block.void ? "opacity-60" : ""}`}
                    >
                      <div className="flex flex-wrap justify-between gap-x-3 gap-y-1 bg-[#f8f9fc] px-3 py-2 text-[0.86rem]">
                        <span>
                          <strong className="font-semibold">
                            {block.title}
                          </strong>{" "}
                          <span className="text-muted">
                            {block.referenceNo}
                          </span>{" "}
                          {block.void ? (
                            <span className={`${badge.base} ${badge.off}`}>
                              {text.void}
                            </span>
                          ) : null}
                        </span>
                        <span>{block.date}</span>
                      </div>
                      {block.lines.map((line, index) => (
                        <div
                          key={index}
                          className="grid grid-cols-[34px_1fr_auto] gap-2 border-t border-divider px-3 py-1.5 text-[0.88rem]"
                        >
                          <span className="font-semibold text-muted">
                            {line.side}
                          </span>
                          <span>{line.name}</span>
                          <span className="tabular-nums">{line.amount}</span>
                        </div>
                      ))}
                      {block.note ? (
                        <div className="border-t border-divider px-3 py-1.5 text-[0.8rem] text-muted">
                          {block.note}
                        </div>
                      ) : null}
                    </div>
                  ))}
                </div>
                <Pager
                  total={doc.blocks.length}
                  state={pager}
                  onChange={setPager}
                />
              </div>
            ) : sideBySide ? (
              <div className="grid gap-3 min-[900px]:grid-cols-2">
                {doc.tables.map((table) => (
                  <div
                    key={table.heading}
                    className="overflow-hidden rounded-2xl bg-surface shadow-[0_1px_3px_rgba(0,0,0,0.05)]"
                  >
                    <ReportTable table={table} />
                  </div>
                ))}
              </div>
            ) : (
              doc.tables.map((table, index) => (
                <div key={index} className="mb-3 last:mb-0">
                  {table.heading ? (
                    <h3 className="mb-1.5 ml-0.5 text-[0.9rem] font-semibold">
                      {table.heading}
                    </h3>
                  ) : null}
                  <TableCard
                    table={table}
                    pager={pager}
                    onPager={setPager}
                    printAll={printAll}
                  />
                </div>
              ))
            )}

            <div className="mt-3 rounded-2xl bg-surface px-3.5 py-3 text-[0.8rem] text-muted shadow-[0_1px_3px_rgba(0,0,0,0.05)]">
              <strong className="font-semibold text-text">{text.notes}</strong>
              <ul className="mt-1.5 list-disc pl-[18px]">
                {doc.notes.map((note) => (
                  <li key={note}>{note}</li>
                ))}
              </ul>
            </div>
          </>
        )}
      </div>
      {children}
    </div>
  );
}
